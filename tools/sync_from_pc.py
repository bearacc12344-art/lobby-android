"""copies the shared add-on pieces from PC Smult (lobby16) into the phone app, so both run add-ons the same way:
the Lua sandbox prelude, the block definitions, the made-by-Smult add-ons and the templates."""
import json, os, re, sys, ast
PC = sys.argv[1] if len(sys.argv) > 1 else "/home/claude/lobby16"
OUT = os.path.join(os.path.dirname(__file__), "..", "src", "addons")
src = open(os.path.join(PC, "addons.py"), encoding="utf-8").read()
prelude = re.search(r"PRELUDE = r'''(.*?)'''", src, re.S).group(1)
perms = ast.literal_eval(re.search(r"PERMISSIONS = (\{.*?\n\})", src, re.S).group(1))
open(os.path.join(OUT, "prelude.js"), "w", encoding="utf-8").write(
    "// generated by tools/sync_from_pc.py from PC Smult's addons.py - don't edit here\n"
    f"export const PRELUDE = {json.dumps(prelude)};\nexport const PERMISSIONS = {json.dumps(perms, ensure_ascii=False)};\n")
sys.path.insert(0, PC)
os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
import blocks as B
defs = {k: {kk: vv for kk, vv in v.items()} for k, v in B.BLOCKS.items()}
for v in defs.values():
    if "fields" in v:
        v["fields"] = {n: list(spec) for n, spec in v["fields"].items()}
open(os.path.join(OUT, "blocksdef.js"), "w", encoding="utf-8").write(
    "// generated by tools/sync_from_pc.py from PC Smult's blocks.py - don't edit here\n"
    f"export const CATS = {json.dumps(B.CATS, ensure_ascii=False)};\nexport const BLOCKS = {json.dumps(defs, ensure_ascii=False)};\n"
    f"export const STARTER = {json.dumps(B.STARTER, ensure_ascii=False)};\n")
def pack(folder):
    out = {}
    for d in sorted(os.listdir(folder)):
        p = os.path.join(folder, d)
        if not os.path.isdir(p):
            continue
        files = {f: open(os.path.join(p, f), encoding="utf-8").read() for f in os.listdir(p) if f.endswith((".lua", ".json", ".md", ".txt"))}
        out[d] = {"man": json.loads(files["addon.json"]), "files": files}
    return out
json.dump({"bundled": pack(os.path.join(PC, "assets", "addons")), "templates": pack(os.path.join(PC, "assets", "addon_templates"))},
          open(os.path.join(OUT, "bundled.json"), "w", encoding="utf-8"), ensure_ascii=False)
print("synced: prelude, blocks", len(defs), "bundled + templates")
